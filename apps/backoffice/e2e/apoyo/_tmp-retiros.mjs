import { chromium } from 'playwright'
import { readFileSync } from 'node:fs'
const base = 'http://127.0.0.1:4301'
const permisos = readFileSync(process.env.PERMISOS_ARCHIVO, 'utf8').split(/\s+/).filter(Boolean)
const token = Buffer.from(JSON.stringify({ permisos, rol: 'PLATAFORMA', sub: 's' })).toString('base64url')
const b = await chromium.launch({ args: ['--disable-features=LocalNetworkAccessChecks'] })
const page = await b.newPage()
await page.route('**/ingreso', async (r) => { const x = await r.fetch(); await r.fulfill({ response: x, body: (await x.text()).replace('</head>', '<meta name="aportaya-gateway" content="/api/v1"></head>') }) }, { times: 1 })
await page.route('**/api/v1/sesiones', async (r) => { if (!r.request().postDataJSON()?.factor) return r.continue(); await r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ sesionId: 's', expiraEn: new Date(Date.now() + 3.6e6).toISOString(), requiereFactorAdicional: false, dispositivoConfiable: true, tokenAcceso: `a.${token}.f` }) }) })
await page.goto(base + '/ingreso')
await page.getByLabel('Correo o teléfono').fill('71234567')
await page.getByLabel('Contraseña', { exact: true }).fill('contrasena-e2e')
await page.getByRole('button', { name: 'Continuar' }).click()
await page.getByLabel('Código de verificación').fill('123456')
await page.waitForURL(/\/tablero$/)
const cdp = await page.context().newCDPSession(page)
await cdp.send('Network.enable'); await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 150, downloadThroughput: 200000, uploadThroughput: 90000 }); await cdp.send('Emulation.setCPUThrottlingRate', { rate: 4 })
const t0 = Date.now()
page.on('request', (r) => r.url().includes('/api/') && console.log('req', Date.now() - t0, r.method(), r.url().replace(base, '')))
page.on('response', (r) => r.url().includes('/api/') && console.log('res', Date.now() - t0, r.status(), r.url().replace(base, '')))
await page.locator('ap-menu-lateral a[href="/operacion/retiros"]').click()
await page.waitForURL(/retiros/)
console.log('url', Date.now() - t0)
for (let i = 0; i < 40; i++) { const t = await page.locator('main#contenido').innerText(); console.log('t', Date.now() - t0, JSON.stringify(t.slice(0, 160))); if (!/Cargando/.test(t) && t.length > 40) break; await page.waitForFunction((p) => document.querySelector('main#contenido')?.innerText !== p, t, { timeout: 5000 }).catch(() => {}) }
await b.close()
